type Row = (string | number)[];

const MONTHS = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];

export function monthLabel(month: string): string {
  return `${MONTHS[Number(month.slice(5, 7)) - 1] ?? month} ${month.slice(0, 4)}`;
}

/** Bank account shown with all but the last 4 digits masked. */
export function maskAccount(acct?: string): string {
  const a = String(acct ?? '').replace(/\s/g, '');
  return a.length > 4 ? `${'•'.repeat(Math.min(8, a.length - 4))}${a.slice(-4)}` : a;
}


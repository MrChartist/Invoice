export type TrKey = Parameters<typeof trT>[0];
/** Translate an error key thrown by a trade / trust lib, else show the message as it is. */
export const trErr = (err: unknown): string => {
  const m = (err as Error)?.message ?? String(err);
  return /^[a-zA-Z_]+$/.test(m) && Object.hasOwn(trT.en, m) ? trT(m as TrKey) : m;
};

const VOUCHER_KEY = {
  Sales: 'vtSales',
  'Credit Note': 'vtCreditNote',
  Receipt: 'vtReceipt',
  Purchase: 'vtPurchase',
  Expense: 'vtExpense',
  Payment: 'vtPayment',
  Opening: 'vtOpening',
  'Debit Note': 'vtDebitNote',
  Journal: 'vtJournal',
  Contra: 'vtContra',
  'Fixed Asset': 'vtFixedAsset',
  Depreciation: 'vtDepreciation',
} as const;

/** Screen name of a stored (English) voucher type; unknown types pass through. */
export function voucherTypeLabel(type: string): string {
  const key = (VOUCHER_KEY as Record<string, (typeof VOUCHER_KEY)[keyof typeof VOUCHER_KEY]>)[type];
  return key ? booksT(key) : type;
}


/** "Monthly" / "Every 2 months" / "Every 10 days" in the interface language. */
export function frequencyText(s: Pick<RecurringSchedule, 'frequency' | 'interval'>): string {
  const k = Math.max(1, Math.floor(Number(s.interval) || 1));
  if (s.frequency === 'custom-days') return k === 1 ? recT('daily') : recT('everyDays', { n: k });
  if (k === 1) return recT(`freq.${s.frequency}`);
  const key = ({ weekly: 'everyWeeks', monthly: 'everyMonths', quarterly: 'everyQuarters', 'half-yearly': 'everyHalfYears', yearly: 'everyYears' } as const)[
    s.frequency as Exclude<Frequency, 'custom-days'>
  ];
  return recT(key, { n: k });
}

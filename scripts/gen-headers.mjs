#!/usr/bin/env node
/**
 * Writes the host header files from scripts/security-headers.mjs.
 *   node scripts/gen-headers.mjs          # rewrite public/_headers, netlify.toml, vercel.json
 *   node scripts/gen-headers.mjs --check  # exit 1 if any file differs from what would be written
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { HEADER_RULES } from './security-headers.mjs';

const ROOT = fileURLToPath(new URL('../', import.meta.url));

export function renderHeadersFile() {
  return HEADER_RULES.map(([path, h]) => [path, ...Object.entries(h).map(([k, v]) => `  ${k}: ${v}`)].join('\n')).join('\n\n') + '\n';
}

const NETLIFY_MARK = '# --- generated by scripts/gen-headers.mjs (edit scripts/security-headers.mjs) ---';

export function renderNetlify(current) {
  const head = current.includes(NETLIFY_MARK)
    ? current.slice(0, current.indexOf(NETLIFY_MARK))
    : current.slice(0, current.search(/^# Security \+ caching headers\./m) >= 0 ? current.search(/^# Security \+ caching headers\./m) : current.search(/^\[\[headers\]\]/m));
  const blocks = HEADER_RULES.map(([path, h]) =>
    ['[[headers]]', `  for = "${path}"`, '  [headers.values]', ...Object.entries(h).map(([k, v]) => `    ${k} = ${JSON.stringify(v)}`)].join('\n'),
  ).join('\n\n');
  return `${head.trimEnd()}\n\n${NETLIFY_MARK}\n${blocks}\n`;
}

const vercelSource = (path) => (path === '/*' ? '/(.*)' : path.endsWith('/*') ? `${path.slice(0, -2)}/(.*)` : path);

export function renderVercel(current) {
  const json = JSON.parse(current);
  json.headers = HEADER_RULES.map(([path, h]) => ({
    source: vercelSource(path),
    headers: Object.entries(h).map(([key, value]) => ({ key, value })),
  }));
  return JSON.stringify(json, null, 2) + '\n';
}

export function outputs() {
  const netlify = readFileSync(join(ROOT, 'netlify.toml'), 'utf8');
  const vercel = readFileSync(join(ROOT, 'vercel.json'), 'utf8');
  return [
    ['public/_headers', renderHeadersFile()],
    ['netlify.toml', renderNetlify(netlify)],
    ['vercel.json', renderVercel(vercel)],
  ];
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const check = process.argv.includes('--check');
  let stale = 0;
  for (const [rel, text] of outputs()) {
    const file = join(ROOT, rel);
    const before = readFileSync(file, 'utf8');
    if (before === text) continue;
    if (check) {
      console.error(`${rel} is out of date - run node scripts/gen-headers.mjs`);
      stale++;
    } else {
      writeFileSync(file, text);
      console.log(`wrote ${rel}`);
    }
  }
  process.exit(stale ? 1 : 0);
}
